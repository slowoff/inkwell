# 1.58.6: text colour picked with nothing selected colours the text typed next
import asyncio, os
from playwright.async_api import async_playwright
PORT = os.environ.get('INKWELL_PORT', '8766')
URL = f'http://localhost:{PORT}/'
fails = []
def check(ok, what):
    print(('ok   ' if ok else 'FAIL ') + what)
    if not ok: fails.append(what)
COL = """w => { const el = document.querySelector('.it-text'); const tw = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
  for(let n; (n = tw.nextNode());){ if(n.data.includes(w)) return getComputedStyle(n.parentNode).color; } return null; }"""
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1180, 'height': 820})
        await ctx.route('**/*.supabase.co/**', lambda r: r.abort())
        page = await ctx.new_page(); errs = []
        page.on('pageerror', lambda e: errs.append(str(e)))
        await page.goto(URL); await page.wait_for_timeout(3000)
        await page.wait_for_function('window.__inkwell && window.__inkwell.cur', timeout=15000)
        await page.evaluate("async () => { await __inkwell.newPage(); }"); await page.wait_for_timeout(300)
        await page.evaluate("() => __inkwell.setTool('text')")
        st = await page.evaluate("(() => { const r = document.getElementById('stage').getBoundingClientRect(); return [r.left, r.top]; })()")
        await page.mouse.click(st[0] + 250, st[1] + 200); await page.wait_for_timeout(300)
        await page.keyboard.type('black ')
        await page.click('#fmtBar [data-act="tcolor"]'); await page.click('#tpalette [data-tc="#1F4FCF"]'); await page.wait_for_timeout(100)
        await page.keyboard.type('blue words'); await page.wait_for_timeout(200)
        check(await page.evaluate(COL, 'blue') == 'rgb(31, 79, 207)', 'colour picked with nothing selected: typed text is blue')
        check(await page.evaluate(COL, 'black') != 'rgb(31, 79, 207)', 'text before it unchanged')
        await page.click('#fmtBar [data-act="tcolor"]'); await page.click('#tpalette [data-tc=""]'); await page.wait_for_timeout(100)
        await page.keyboard.type(' plain'); await page.wait_for_timeout(200)
        check(await page.evaluate(COL, 'plain') == await page.evaluate(COL, 'black'), 'default colour picked: back to normal')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(300)
        html = await page.evaluate("[...__inkwell.cur.items.values()].find(i => i.t === 'x').html")
        check('#1f4fcf' in html.lower() or '31, 79, 207' in html, f'saved ({html})')
        check('254' not in html, 'no marker colour left in the saved text')
        # 1.58.7: picked colour stays for new boxes; the A underline shows it
        UL = "getComputedStyle(document.querySelector('#fmtBar .tcolor-a')).borderBottomColor"
        await page.click('#fmtBar [data-act="tcolor"]') if not await page.evaluate("document.getElementById('fmtBar').classList.contains('idle')") else None
        await page.mouse.click(st[0] + 250, st[1] + 400); await page.wait_for_timeout(300)
        await page.click('#fmtBar [data-act="tcolor"]'); await page.click('#tpalette [data-tc="#C2362B"]'); await page.wait_for_timeout(100)
        await page.keyboard.type('red one'); await page.keyboard.press('Escape'); await page.wait_for_timeout(300)
        check(await page.evaluate(UL) == 'rgb(194, 54, 43)', 'line under A shows red')
        await page.mouse.click(st[0] + 250, st[1] + 550); await page.wait_for_timeout(300)
        await page.keyboard.type('new box text'); await page.wait_for_timeout(200)
        c = await page.evaluate("(() => { const n = [...document.querySelectorAll('.it-text')].find(e => e.textContent.includes('new box')); const tw = document.createTreeWalker(n, NodeFilter.SHOW_TEXT); const t = tw.nextNode(); return getComputedStyle(t.parentNode).color; })()")
        check(c == 'rgb(194, 54, 43)', f'a new box writes in the picked colour ({c})')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(300)
        await page.reload(); await page.wait_for_timeout(3000)
        await page.wait_for_function('window.__inkwell && window.__inkwell.cur', timeout=15000)
        await page.evaluate("() => __inkwell.setTool('text')"); await page.wait_for_timeout(200)
        check(await page.evaluate(UL) == 'rgb(194, 54, 43)', 'colour remembered after a reload')
        await page.mouse.click(st[0] + 600, st[1] + 300); await page.wait_for_timeout(300)
        await page.click('#fmtBar [data-act="tcolor"]'); await page.click('#tpalette [data-tc=""]'); await page.wait_for_timeout(100)
        await page.keyboard.press('Escape'); await page.wait_for_timeout(300)
        await page.mouse.click(st[0] + 600, st[1] + 500); await page.wait_for_timeout(300)
        await page.keyboard.type('normal again'); await page.wait_for_timeout(200)
        c2 = await page.evaluate("(() => { const n = [...document.querySelectorAll('.it-text')].find(e => e.textContent.includes('normal again')); const tw = document.createTreeWalker(n, NodeFilter.SHOW_TEXT); const t = tw.nextNode(); return [getComputedStyle(t.parentNode).color, getComputedStyle(n).color]; })()")
        check(c2[0] == c2[1], f'after picking the default colour new boxes write normally ({c2})')
        # 1.58.9: custom colour (system picker simulated: the label is tapped, focus moves away, a value comes back)
        await page.mouse.click(st[0] + 600, st[1] + 650); await page.wait_for_timeout(300)
        await page.keyboard.type('abc ')
        await page.click('#fmtBar [data-act="tcolor"]'); await page.wait_for_timeout(100)
        await page.click('#tcolorPop .custom-color span'); await page.wait_for_timeout(100)
        await page.evaluate("() => { const i = document.getElementById('tCustom'); i.focus(); }"); await page.wait_for_timeout(400)
        still = await page.evaluate("!!document.querySelector('.it-text[contenteditable=true]')")
        check(still, 'the box stays open while the colour picker is up')
        await page.evaluate("() => { const i = document.getElementById('tCustom'); i.value = '#ff00aa'; i.dispatchEvent(new Event('input', {bubbles: true})); i.dispatchEvent(new Event('change', {bubbles: true})); }")
        await page.wait_for_timeout(200)
        await page.keyboard.type('pink'); await page.wait_for_timeout(200)
        cp = await page.evaluate("(() => { const n = [...document.querySelectorAll('.it-text')].find(e => e.textContent.includes('pink')); const tw = document.createTreeWalker(n, NodeFilter.SHOW_TEXT); for(let t; (t = tw.nextNode());) if(t.data.includes('pink')) return getComputedStyle(t.parentNode).color; })()")
        check(cp == 'rgb(255, 0, 170)', f'custom colour: typed text in that colour ({cp})')
        check(await page.evaluate(UL) == 'rgb(255, 0, 170)', 'line under A shows the custom colour')
        check(not errs, 'no page errors ' + '; '.join(errs[:3]))
        await b.close()
    print('PASS' if not fails else f'{len(fails)} FAILED')
    raise SystemExit(1 if fails else 0)
asyncio.run(main())

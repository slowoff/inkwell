# 1.84: Pencil menu: the outer ring follows the inner ring.
import asyncio, os
from playwright.async_api import async_playwright
PORT = os.environ.get('INKWELL_PORT', '8766')
URL = f'http://localhost:{PORT}/'
fails = []
def check(ok, what):
    print(('ok   ' if ok else 'FAIL ') + what)
    if not ok: fails.append(what)
OUT = """() => { const g = [...document.querySelectorAll('#wheel .wh-seg')]; const n = __inkwell; return g.filter(b => document.querySelector(`#wheel .wh-i[data-i="${b.dataset.i}"]`).style && +b.dataset.i >= 5).map(b => b.dataset.w + (b.dataset.v ? ':' + b.dataset.v : '')); }"""
POS = """s => { const g = document.querySelector('#wheel .wh-seg' + s); const ic = document.querySelector(`#wheel .wh-i[data-i="${g.dataset.i}"]`).getBoundingClientRect(); return [ic.left + ic.width / 2, ic.top + ic.height / 2]; }"""
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1180, 'height': 820}, device_scale_factor=2)
        await ctx.route('**/*.supabase.co/**', lambda r: r.abort())
        page = await ctx.new_page(); errs = []
        page.on('pageerror', lambda e: errs.append(str(e)))
        await page.goto(URL)
        await page.wait_for_function('navigator.serviceWorker && navigator.serviceWorker.controller', timeout=30000); await page.wait_for_timeout(2500)
        await page.wait_for_function('window.__inkwell && window.__inkwell.cur', timeout=15000)
        await page.evaluate("async () => { await __inkwell.newPage(); __inkwell.setTool('pen'); }"); await page.wait_for_timeout(300)
        P = lambda s: page.evaluate(POS, s)
        opened = lambda: page.evaluate("!document.getElementById('wheel').hidden")
        async def op(): await page.evaluate("__inkwell.openWheel(700, 420)"); await page.wait_for_timeout(200)
        async def go(s): x, y = await P(s); await page.mouse.move(x, y, steps=2); await page.wait_for_timeout(300 if 'tool' in s or 'undo' in s else 60)
        await op()
        o = await page.evaluate(OUT)
        check(sum(x.startswith('c:') for x in o) == 6 and sum(x.startswith('s:') for x in o) == 3, f'pen: colours and sizes ({o})')
        # slide: pen -> highlighter -> a highlighter colour
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(100)
        await go('[data-w=tool][data-v=hl]')
        o = await page.evaluate(OUT); favs = await page.evaluate("__inkwell.prefs.hlFavs")
        check([x[2:] for x in o if x.startswith('c:')] == favs and await page.evaluate("!!document.querySelector('#wheel .wh-col.hl')"), f'highlighter hovered: its colours ({o})')
        if os.environ.get('GSHOT'): await page.screenshot(path=os.environ['GSHOT'] + '-hl.png')
        check(await page.evaluate("__inkwell.prefs.tool") == 'pen', 'only looking changes nothing yet')
        # crossing the inner ring quickly on the way out does not change what is aimed at
        await page.mouse.up(); await page.wait_for_timeout(150); await page.evaluate("__inkwell.closeWheel(); __inkwell.setTool('pen')"); await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(60)
        x, y = await P('[data-w=tool][data-v=lasso]')
        o = await page.evaluate("([x, y, out]) => { document.getElementById('wheel').dispatchEvent(new PointerEvent('pointermove', {pointerId: 1, clientX: x, clientY: y, bubbles: true})); return eval('(' + out + ')')(); }", [x, y, OUT])
        check(any(k.startswith('c:') for k in o), f'crossing quickly keeps the ring ({o})')
        await page.mouse.up(); await page.wait_for_timeout(150); await page.evaluate("__inkwell.closeWheel(); __inkwell.setTool('pen')"); await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(60)
        await go('[data-w=tool][data-v=hl]')
        await go(f'[data-w=c][data-v="{favs[2]}"]'); await page.mouse.up(); await page.wait_for_timeout(200)
        d = await page.evaluate("[__inkwell.prefs.tool, __inkwell.prefs.hl.c, !document.getElementById('wheel').hidden]")
        check(d == ['hl', favs[2], False], f'picking it sets highlighter and colour, closes ({d})')
        await page.evaluate("__inkwell.setTool('pen')"); await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(100)
        await go('[data-w=tool][data-v=eraser]')
        o = await page.evaluate(OUT)
        check(o[:2] == ['em:stroke', 'em:area'] and sum(x.startswith('s:') for x in o) == 3 and not any(x.startswith('c:') for x in o), f'eraser: modes and sizes, no colours ({o})')
        if os.environ.get('GSHOT'): await page.screenshot(path=os.environ['GSHOT'] + '-er.png')
        await go('[data-w=em][data-v=area]'); await page.mouse.up(); await page.wait_for_timeout(200)
        d = await page.evaluate("[__inkwell.prefs.tool, __inkwell.prefs.eraser.mode, !document.getElementById('wheel').hidden]")
        check(d == ['eraser', 'area', False], f'Partial sets eraser and mode ({d})')
        await page.evaluate("__inkwell.prefs.eraser.mode = 'stroke'; __inkwell.setTool('pen')"); await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(100)
        await go('[data-w=tool][data-v=lasso]')
        o = await page.evaluate(OUT)
        check(o == ['lm:free', 'lm:box', 'lm:tap', 'paste'], f'lasso: Free, Box, Tap, Paste ({o})')
        if os.environ.get('GSHOT'): await page.screenshot(path=os.environ['GSHOT'] + '-la.png')
        await go('[data-w=lm][data-v=box]'); await page.mouse.up(); await page.wait_for_timeout(200)
        d = await page.evaluate("[__inkwell.prefs.tool, __inkwell.prefs.lassoMode]")
        check(d == ['lasso', 'box'], f'Box sets lasso and mode ({d})')
        await page.evaluate("__inkwell.prefs.lassoMode = 'free'; __inkwell.setTool('pen'); __inkwell.addItems([{t:'x', id:'xr', x:50, y:50, w:200, fs:1, html:'<p>a</p>'}]); __inkwell.undo()"); await page.wait_for_timeout(200)
        await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(100)
        await go('[data-w=undo]')
        o = await page.evaluate(OUT)
        check(o == ['redo'], f'undo: Redo ({o})')
        await go('[data-w=redo]'); await page.mouse.up(); await page.wait_for_timeout(200)
        check(await page.evaluate("__inkwell.cur.items.has('xr')") and not await opened(), 'Redo brings it back')
        # plain tap on an inner option
        await op()
        await go('[data-w=tool][data-v=hl]'); await page.mouse.down(); await page.wait_for_timeout(60); await page.mouse.up(); await page.wait_for_timeout(200)
        d = await page.evaluate("[__inkwell.prefs.tool, !document.getElementById('wheel').hidden]")
        check(d == ['hl', False], f'a tap on a tool picks it and closes ({d})')
        # sizes follow
        await page.evaluate("__inkwell.setTool('pen')"); await op()
        await go('[data-w=tool][data-v=pen]'); await page.mouse.down(); await page.wait_for_timeout(100)
        await go('[data-w=tool][data-v=hl]')
        await go('[data-w=s][data-slot="2"]'); await page.mouse.up(); await page.wait_for_timeout(200)
        d = await page.evaluate("[__inkwell.prefs.tool, __inkwell.prefs.hl.s]")
        check(d[0] == 'hl' and d[1] == 75, f'size applies to the shown tool ({d})')
        check(not errs, f'no page errors {errs}')
        await b.close()
asyncio.run(main())
if fails: raise SystemExit(1)
